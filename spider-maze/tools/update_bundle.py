import os
import json
import base64
import shutil

ROOT = r"C:\Skills\Youtube\MAZE_GAME\spider-maze\audio"
DATA_FILE = os.path.join(ROOT, "audio-data.js")

# 1. Read existing AUDIO_DATA
with open(DATA_FILE, "r", encoding="utf-8") as f:
    content = f.read()

prefix = "window.AUDIO_DATA = "
idx = content.find(prefix)
if idx != -1:
    raw_json = content[idx + len(prefix):].rstrip().rstrip(";")
    data = json.loads(raw_json)
else:
    raise ValueError("Could not find window.AUDIO_DATA in " + DATA_FILE)

# 2. Update action and calm music stems
act_path = os.path.join(ROOT, "music", "action.wav")
calm_path = os.path.join(ROOT, "music", "calm.wav")

with open(act_path, "rb") as f:
    data["music"]["action"] = base64.b64encode(f.read()).decode("ascii")

with open(calm_path, "rb") as f:
    data["music"]["calm"] = base64.b64encode(f.read()).decode("ascii")

with open(DATA_FILE, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/make_audio.py. High-energy Brazilian Phonk (NO BATIDÃO - ZXKAI) + Punchy SFX bundle.\nwindow.AUDIO_DATA = " + json.dumps(data) + ";\n")

print(f"Updated audio-data.js successfully. Total size: {os.path.getsize(DATA_FILE)} bytes.")

# 3. Copy full song to no_batidao_zxkai.wav
src_song = os.path.join(ROOT, "music", "no_batidao.wav")
dest_maze = os.path.join(ROOT, "music", "no_batidao_zxkai.wav")
dest_ref = r"C:\Skills\Youtube\MAZE_GAME\Reference_Development\no_batidao_zxkai.wav"

shutil.copyfile(src_song, dest_maze)
shutil.copyfile(src_song, dest_ref)
print("Copied full song to", dest_maze, "and", dest_ref)

# 4. Remove test_clip.wav if exists
test_clip = os.path.join(ROOT, "music", "test_clip.wav")
if os.path.exists(test_clip):
    os.remove(test_clip)
    print("Cleaned up test_clip.wav")
